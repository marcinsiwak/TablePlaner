let _lang = (function () {
  const supported = ['pl', 'en', 'es', 'it', 'fr', 'de', 'uk'];
  try {
    const saved = localStorage.getItem('tp_lang');
    if (saved && supported.includes(saved)) return saved;
  } catch (_) {}
  const navLangs = navigator.languages && navigator.languages.length
    ? navigator.languages
    : [navigator.language || 'pl'];
  for (const lang of navLangs) {
    const code = lang.split('-')[0].toLowerCase();
    if (supported.includes(code)) return code;
  }
  return 'pl';
}());

function t(key, params) {
  const dict = TRANSLATIONS[_lang] || TRANSLATIONS.pl;
  let str = dict[key] !== undefined ? dict[key] : (TRANSLATIONS.pl[key] !== undefined ? TRANSLATIONS.pl[key] : key);
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), v);
    }
  }
  return str;
}

function setLanguage(code) {
  _lang = code;
  try { localStorage.setItem('tp_lang', code); } catch (_) {}
  document.documentElement.lang = code;
  applyLocale();
}

function applyLocale() {
  const sel = document.getElementById('langSelect');
  if (sel) sel.value = _lang;
  document.documentElement.lang = _lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });

  if (window.renderGuestList)   window.renderGuestList();
  if (window.renderSidebar)     window.renderSidebar();
  if (window.renderCategoryList) window.renderCategoryList();
  if (window.renderSessionList) window.renderSessionList();
  if (window.renderSeatPanel && window.selected !== null) window.renderSeatPanel();
  if (window.pendingHeaders && window.pendingHeaders.length > 0) {
    if (window.renderColumnPicker) window.renderColumnPicker();
    if (window.applyMapping) window.applyMapping();
  }
  const overlay = document.getElementById('guestPickerOverlay');
  if (overlay && overlay.style.display !== 'none' && window.renderPicker) window.renderPicker();
}
